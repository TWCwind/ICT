param([switch]$NoBrowser)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$backendDir = Join-Path $projectRoot 'backend'
$frontendDir = Join-Path $projectRoot 'frontend-vue'
$frontendIndex = Join-Path $frontendDir 'dist\index.html'
$sourceDataDir = Join-Path $projectRoot 'roadshow-seed'
if (!(Test-Path -LiteralPath $sourceDataDir)) { $sourceDataDir = Join-Path $backendDir 'data' }
$roadshowDataDir = Join-Path $projectRoot 'roadshow-data'
$pythonExe = Join-Path $backendDir '.venv\Scripts\python.exe'
if (!(Test-Path -LiteralPath $pythonExe)) {
  $pythonCommand = Get-Command python -ErrorAction Stop
  $pythonExe = $pythonCommand.Source
}
$nodeExe = (Get-Command node -ErrorAction Stop).Source

if (!(Test-Path -LiteralPath $frontendIndex)) {
  throw 'Frontend build is missing. Run npm ci and npm run build in frontend-vue first.'
}
& $pythonExe @('-c', 'import fastapi, uvicorn, fitz, pptx')
if ($LASTEXITCODE -ne 0) { throw 'Backend dependencies are missing. Run the dependency installer first.' }

# roadshow-data is disposable runtime data. Preserve an unknown directory;
# only the marker-managed copy is replaced on the next run.
if (Test-Path -LiteralPath $roadshowDataDir) {
  $marker = Join-Path $roadshowDataDir '.roadshow-runtime'
  if (Test-Path -LiteralPath $marker) {
    Remove-Item -LiteralPath $roadshowDataDir -Recurse -Force
  } else {
    $backup = "$roadshowDataDir.backup-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    Move-Item -LiteralPath $roadshowDataDir -Destination $backup
    Write-Host "已保留未标记的旧路演数据：$backup" -ForegroundColor Yellow
  }
}
New-Item -ItemType Directory -Force -Path $roadshowDataDir | Out-Null
Get-ChildItem -LiteralPath $sourceDataDir -Force | Copy-Item -Destination $roadshowDataDir -Recurse -Force
Set-Content -LiteralPath (Join-Path $roadshowDataDir '.roadshow-runtime') -Value 'generated by start-roadshow.ps1' -Encoding UTF8

$selectedBackendPort = $null
foreach ($candidate in 8000..8010) {
  if (!(Get-NetTCPConnection -LocalPort $candidate -State Listen -ErrorAction SilentlyContinue)) {
    $selectedBackendPort = $candidate
    break
  }
}
if ($null -eq $selectedBackendPort) { throw 'Backend ports 8000-8010 are busy.' }

$selectedFrontendPort = $null
foreach ($candidate in 5173..5183) {
  if (!(Get-NetTCPConnection -LocalPort $candidate -State Listen -ErrorAction SilentlyContinue)) {
    $selectedFrontendPort = $candidate
    break
  }
}
if ($null -eq $selectedFrontendPort) { throw 'Frontend ports 5173-5183 are busy.' }

$env:PYTHONPATH = $backendDir
$env:DATA_DIR = $roadshowDataDir
$env:FRONTEND_DIST = Join-Path $frontendDir 'dist'
$env:APP_ENV = 'roadshow'
$env:ROADSHOW_BACKEND_PORT = "$selectedBackendPort"
$logDir = Join-Path $projectRoot 'roadshow-logs'
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$backendOut = Join-Path $logDir 'server.out.log'
$backendErr = Join-Path $logDir 'server.err.log'
$frontendOut = Join-Path $logDir 'frontend.out.log'
$frontendErr = Join-Path $logDir 'frontend.err.log'
$backend = $null
$frontend = $null
try {
  $backend = Start-Process -FilePath $pythonExe -WorkingDirectory $backendDir `
    -ArgumentList @('-m', 'uvicorn', 'app.main:app', '--host', '127.0.0.1', '--port', "$selectedBackendPort") `
    -RedirectStandardOutput $backendOut -RedirectStandardError $backendErr -WindowStyle Hidden -PassThru
  $frontend = Start-Process -FilePath $nodeExe -WorkingDirectory $frontendDir `
    -ArgumentList @('scripts/dev-server.mjs', '--host', '127.0.0.1', '--port', "$selectedFrontendPort") `
    -RedirectStandardOutput $frontendOut -RedirectStandardError $frontendErr -WindowStyle Hidden -PassThru

  $backendUrl = "http://127.0.0.1:$selectedBackendPort"
  $frontendUrl = "http://127.0.0.1:$selectedFrontendPort"
  $backendReady = $false
  $frontendReady = $false
  foreach ($attempt in 1..50) {
    if ($backend.HasExited -or $frontend.HasExited) { break }
    try { if ((Invoke-WebRequest -UseBasicParsing -Uri "$backendUrl/api/health" -TimeoutSec 2).StatusCode -eq 200) { $backendReady = $true } } catch {}
    try { if ((Invoke-WebRequest -UseBasicParsing -Uri $frontendUrl -TimeoutSec 2).StatusCode -eq 200) { $frontendReady = $true } } catch {}
    if ($backendReady -and $frontendReady) { break }
    Start-Sleep -Milliseconds 400
  }
  if (!$backendReady) { throw "Backend failed to start. See $backendErr" }
  if (!$frontendReady) { throw "Frontend failed to start. See $frontendErr" }
  Write-Host "Roadshow backend: $backendUrl" -ForegroundColor Green
  Write-Host "Roadshow frontend: $frontendUrl" -ForegroundColor Green
  Write-Host 'Using clean local roadshow data; no external model or online service is called.' -ForegroundColor Cyan
  if (!$NoBrowser) { Start-Process $frontendUrl }
  Wait-Process -Id $backend.Id
} finally {
  foreach ($process in @($frontend, $backend)) {
    if ($null -ne $process -and !$process.HasExited) {
      Stop-Process -Id $process.Id -Force -ErrorAction SilentlyContinue
    }
  }
}
